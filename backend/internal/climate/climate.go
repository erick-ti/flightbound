// Package climate holds the typical weather of each supported place: monthly
// normals computed once from ERA5-Land reanalysis data by cmd/climatenormals
// and saved in normals.json.
package climate

import (
	_ "embed"
	"fmt"
	"strconv"
	"time"

	"github.com/erick-ti/flightbound/backend/internal/era5"
	"github.com/erick-ti/flightbound/backend/internal/places"
)

// Month is a calendar month's typical weather at a place, rounded for
// display: whole degrees, whole millimetres, and inches to one decimal
// place, such as "3.5".
type Month struct {
	Month           time.Month
	HighC, HighF    int
	LowC, LowF      int
	PrecipitationMM int
	PrecipitationIn string
}

// Normals holds monthly normals for the places that have them.
type Normals struct {
	period  era5.Period
	byPlace map[string][12]era5.Month
}

// normalsJSON is generated by cmd/climatenormals; do not edit it by hand.
//
//go:embed normals.json
var normalsJSON []byte

var embedded = mustParse(normalsJSON)

func mustParse(data []byte) *Normals {
	n, err := Parse(data)
	if err != nil {
		panic("climate: normals.json: " + err.Error())
	}
	return n
}

// Parse reads a normals document. Every place in it must be a supported
// place; a supported place it lacks simply has no normals.
func Parse(data []byte) (*Normals, error) {
	doc, err := era5.UnmarshalNormals(data)
	if err != nil {
		return nil, err
	}
	n := &Normals{period: doc.Period, byPlace: make(map[string][12]era5.Month, len(doc.Places))}
	for _, p := range doc.Places {
		if _, ok := places.Lookup(p.ID); !ok {
			return nil, fmt.Errorf("normals for %q, which is not a supported place", p.ID)
		}
		n.byPlace[p.ID] = p.Months
	}
	return n, nil
}

// Embedded returns the saved normals.
func Embedded() *Normals {
	return embedded
}

// Period returns the first and last years the normals average over.
func (n *Normals) Period() (first, last int) {
	return n.period.First, n.period.Last
}

// Typical returns the place's typical weather for each of the months, in
// the same order. It reports false when the place has no normals.
func (n *Normals) Typical(placeID string, months []time.Month) ([]Month, bool) {
	normals, ok := n.byPlace[placeID]
	if !ok {
		return nil, false
	}
	out := make([]Month, len(months))
	for i, m := range months {
		v := normals[m-1]
		out[i] = Month{
			Month:           m,
			HighC:           celsius(v.HighTenthsC),
			HighF:           fahrenheit(v.HighTenthsC),
			LowC:            celsius(v.LowTenthsC),
			LowF:            fahrenheit(v.LowTenthsC),
			PrecipitationMM: millimetres(v.PrecipitationTenthsMM),
			PrecipitationIn: inches(v.PrecipitationTenthsMM),
		}
	}
	return out, true
}

// The conversions round once, from the stored tenths, with integer
// arithmetic and halves away from zero.

func celsius(tenths int) int { return divRound(tenths, 10) }

// fahrenheit is C × 9/5 + 32 with C = tenths/10.
func fahrenheit(tenths int) int { return divRound(tenths*9+1600, 50) }

func millimetres(tenths int) int { return divRound(tenths, 10) }

// inches gives tenths of a millimetre in inches (25.4 mm) to one decimal
// place.
func inches(tenths int) string {
	t := divRound(tenths*10, 254)
	return strconv.Itoa(t/10) + "." + strconv.Itoa(t%10)
}

// divRound divides by an even, positive d, rounding halves away from zero.
func divRound(n, d int) int {
	if n < 0 {
		return -((-n + d/2) / d)
	}
	return (n + d/2) / d
}
